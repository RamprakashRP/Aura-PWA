export function getBankById(id?: string | null): BankInfo {
  if (!id) return BANK_CATALOG[BANK_CATALOG.length - 1];
  return BANK_CATALOG.find((b) => b.id.toLowerCase() === id.toLowerCase()) || BANK_CATALOG[BANK_CATALOG.length - 1];
}

export function getBanksByCountry(country: 'CA' | 'IN' | 'GLOBAL'): BankInfo[] {
  return BANK_CATALOG.filter((b) => b.country === country || b.country === 'GLOBAL');
}
